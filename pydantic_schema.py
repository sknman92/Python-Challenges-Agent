from datetime import datetime
from pydantic import BaseModel, Field
from typing import Literal

#-------------------------------------------
# Defining pydantic schema for the scorecard
# After each attempt to solve question, 
# LLM scores the attempt and stores the score along
# with other medtadata in a SQL Lite db for efficient retrieval
#-------------------------------------------

class ScorecardRow(BaseModel):
    Date: datetime = Field(
        description="timestamp of the attempt"
    )
    Main_Topic: str = Field(
        description="Main topic of the challenge, e.g. 'Pandas Aggregation', 'Error Handling', 'Unit Tests', 'Context Management'"
    )
    Score: int = Field(
        description="score of the attempt. Generated by LLM. Acceptable scores range from 1-10, with 10 being the best"
    )
    Feedback: str = Field(
        description="Limit to 100 lines. A short and concise feedback of the student's attempt, including things done well and" \
        "areas for improvement"
    )


